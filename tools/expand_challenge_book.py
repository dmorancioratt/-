def replace_media(docx_path):
    import zipfile, tempfile, shutil
    files = sorted(IMG.glob("*.png"), key=lambda p: int(p.name.split("图")[1].split("_")[0]))
    tmp = Path(tempfile.mkdtemp())
    out = tmp / docx_path.name
    with zipfile.ZipFile(docx_path, "r") as zin, zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zout:
        media = sorted([n for n in zin.namelist() if n.startswith("word/media/") and n.lower().endswith(".png")])
        mapping = {media[i]: files[i].read_bytes() for i in range(min(10, len(media), len(files)))}
        for item in zin.infolist():
            zout.writestr(item, mapping.get(item.filename, zin.read(item.filename)))
    shutil.copy2(out, docx_path)
    shutil.rmtree(tmp)


